    급여지급일: 20,

    // 연도별 최저시급(원). ★매년 갱신★ — 새 해가 오면 줄을 추가하세요. 예)  '2027': 10800
    최저시급: { '2023': 9620, '2024': 9860, '2025': 10030, '2026': 10320 },
    // 최저연봉 = 최저시급 × 12 × (이 계수), 천원 절상.
    //  계수 = 월 소정근로시간 환산값(주40h·주휴·연장 반영). 거의 바뀌지 않음.
    최저연봉_월환산계수: 274.17857142857144,

